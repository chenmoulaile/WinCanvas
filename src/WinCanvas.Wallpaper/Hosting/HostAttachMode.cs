namespace WinCanvas.Wallpaper.Hosting;

/// <summary>
/// 壁纸宿主窗口与目标窗口的挂接方式（WP1 阶段 A 引入，双路径策略）。
/// </summary>
/// <remarks>
/// 路径语义（与总提示词 WP1 阶段 A 规格一一对应）：
/// - <see cref="Embed"/>（A1，首选）：宿主以 WS_CHILD 直接嵌入目标窗口（跨进程 SetParent 语义），
///   宿主矩形 = 目标客户区，沉到目标子窗口 Z 序底部。目标窗口移动时子窗口自动跟随，
///   仅需监听客户区尺寸变化与 Z 序被调整两种事件。
///   已知风险：跨进程父子关系会隐式附加输入队列，个别应用可能出现焦点 / 快捷键异常。
/// - <see cref="Follow"/>（A2，回退）：宿主为 WS_POPUP 顶层无主窗口，跟随目标外接矩形、
///   Z 序钉在目标正下方。壁纸在目标「身后」，要求目标带 WS_EX_LAYERED 且 alpha &lt; 255 才可见，
///   因此进入 A2 时若目标不透明会自动应用轻度透明（alpha=220）。
/// 降级规则：每个会话先尝试 A1；A1 创建失败（UIPI 拒绝、目标已销毁等）直接降级 A2；
/// A1 挂接成功后 30 秒观察期内若检测到焦点异常（宿主意外获得焦点）或父子关系被外力破坏，
/// 自动销毁 A1 宿主并按 A2 重建。会话记录最终所用路径，UI 状态文本可见。
/// </remarks>
public enum HostAttachMode
{
    /// <summary>A1 跨进程子窗口嵌入：宿主是目标的 WS_CHILD 子窗口，矩形 = 目标客户区。</summary>
    Embed = 1,

    /// <summary>A2 跟随窗口：宿主为独立顶层窗口，矩形跟随目标外接框、Z 序钉在目标正下方。</summary>
    Follow = 2,
}
